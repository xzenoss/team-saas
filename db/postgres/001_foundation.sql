-- Gather PostgreSQL schema contract for issue #6 (isolated CI only).
-- Not a production cutover or data migration from SQLite.
-- All tenant predicates MUST be set in a trusted, authenticated transaction;
-- app.workspace_id is not an independent security credential.
BEGIN;

CREATE TABLE users (
    id text PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    password text NOT NULL
);

CREATE TABLE workspaces (
    id text PRIMARY KEY,
    name text NOT NULL
);

CREATE TABLE members (
    workspace_id text NOT NULL REFERENCES workspaces(id),
    user_id text NOT NULL REFERENCES users(id),
    role text NOT NULL CHECK (role IN ('owner', 'admin', 'member')),
    PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE sessions (
    token text PRIMARY KEY,
    user_id text NOT NULL REFERENCES users(id),
    workspace_id text NOT NULL REFERENCES workspaces(id),
    csrf text NOT NULL,
    expires double precision NOT NULL,
    FOREIGN KEY (workspace_id, user_id)
        REFERENCES members (workspace_id, user_id)
);

CREATE TABLE projects (
    id text PRIMARY KEY,
    workspace_id text NOT NULL REFERENCES workspaces(id),
    name text NOT NULL,
    description text NOT NULL,
    color text NOT NULL,
    created double precision NOT NULL,
    UNIQUE (workspace_id, id)
);

CREATE TABLE tasks (
    id text PRIMARY KEY,
    workspace_id text NOT NULL REFERENCES workspaces(id),
    project_id text NOT NULL,
    title text NOT NULL,
    description text NOT NULL,
    status text NOT NULL CHECK (status IN ('todo', 'progress', 'done')),
    priority text NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
    assignee_id text,
    due text NOT NULL,
    created double precision NOT NULL,
    FOREIGN KEY (workspace_id, project_id)
        REFERENCES projects(workspace_id, id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, assignee_id)
        REFERENCES members(workspace_id, user_id)
);

CREATE TABLE invites (
    token text PRIMARY KEY,
    workspace_id text NOT NULL REFERENCES workspaces(id),
    expires double precision NOT NULL,
    created_by text NOT NULL REFERENCES users(id)
);

CREATE TABLE activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text NOT NULL REFERENCES workspaces(id),
    actor text NOT NULL,
    message text NOT NULL,
    created double precision NOT NULL
);

CREATE TABLE auth_rate_hits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_hash text NOT NULL,
    attempted_at double precision NOT NULL
);
CREATE INDEX idx_auth_rate_hits_key_time ON auth_rate_hits(key_hash, attempted_at);

-- Defense in depth for tenant-specific rows.
-- Runtime roles should be non-owner, non-superuser and not BYPASSRLS.
-- Production authentication/bootstrap access to users/sessions is NOT designed
-- in this contract. Do not grant application roles broad public users access.
ALTER TABLE workspaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspaces FORCE ROW LEVEL SECURITY;
CREATE POLICY workspace_tenant ON workspaces
    USING (id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (id = NULLIF(current_setting('app.workspace_id', true), ''));

-- Membership existence is checked by composite constraints as well as RLS.
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE members FORCE ROW LEVEL SECURITY;
CREATE POLICY member_tenant ON members
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions FORCE ROW LEVEL SECURITY;
CREATE POLICY session_tenant ON sessions
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects FORCE ROW LEVEL SECURITY;
CREATE POLICY project_tenant ON projects
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks FORCE ROW LEVEL SECURITY;
CREATE POLICY task_tenant ON tasks
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

ALTER TABLE invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE invites FORCE ROW LEVEL SECURITY;
CREATE POLICY invite_tenant ON invites
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

ALTER TABLE activity ENABLE ROW LEVEL SECURITY;
ALTER TABLE activity FORCE ROW LEVEL SECURITY;
CREATE POLICY activity_tenant ON activity
    USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''))
    WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), ''));

COMMIT;
